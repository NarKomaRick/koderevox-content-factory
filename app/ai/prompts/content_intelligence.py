def build_content_intelligence_prompt(content: str, user_notes: str = "") -> str:
    notes = f"\nДополнительный контекст пользователя:\n{user_notes}" if user_notes else ""
    return f"""Проанализируй материал как редактор Content Inbox.

Строго разделяй `source_facts` (только явно сказанное в источнике) и `ai_suggestions`
(идеи редактора). Никогда не добавляй в факты придуманные деньги, ущерб, клиентов, сроки,
метрики, причины или последствия.

Оцени content_potential_score честно:
0–20 — почти бесполезно как самостоятельный контент;
21–40 — слабая заметка;
41–60 — полезно как часть материала;
61–80 — хороший самостоятельный контент;
81–100 — сильная история, кейс, необычная проблема или особенно полезный материал.
Не завышай оценку по умолчанию.

Ставь requires_more_context=true только если без деталей качественный самостоятельный материал
заметно проиграет. Задай максимум три конкретных вопроса. Не требуй идеальной транскрипции.

Для видео оцени content_type как talking_head, screen_recording, mixed или unknown только по
доступному контексту. Если данных недостаточно, используй unknown; это рекомендация, а не команда
на обрезку кадра.

Материал:
{content[:100000]}
{notes}
"""
